// set up our class structure
public class Donut {

   // section 1 of our class is always for attributes
   boolean hasSprinkles; 
   String flavor;
   int quantity; 
   double pricePer;

   // section 2 of our class builds a constructor 
   public Donut() {
        hasSprinkles = False;
        flavor = "glazed";
        quantity = 1;
        pricePer = 2.75;
   }
}